/**
 * DKS daily expiry report — PDF renderer.
 *
 * Pure TypeScript: it draws through a tiny `PdfDocument` interface so the SAME
 * layout code is unit tested with vitest (with real jsPDF from node_modules)
 * and bundled into the `send-email` Edge Function (Deno, `npm:jspdf`).
 *
 * The PDF is generated entirely in memory and handed back as bytes; nothing is
 * written to disk, Supabase Storage, or any database table.
 *
 * Layout: A4, one summary table, then one block per record (position number,
 * record label, expiry, days left, status) followed by a two-column
 * field/value list of every active, visible user column in workspace order.
 * Footer on every page: "Generated by DKS" + "Page X of Y".
 *
 * Text limitation: the PDF uses the standard WinAnsi fonts, which cannot encode
 * non-Latin scripts (e.g. Arabic). Such characters are replaced with a visible
 * "?" and the document prints an explicit notice — never blank/garbled output.
 */

import {
  EMPTY_VALUE,
  MAX_DETAIL_RECORDS,
  sanitizePdfText,
  formatReportValue,
  resolveEntryValue,
  type DigestReportModel,
  type ReportColumn,
  type ReportEntry,
} from './digest-report.ts';

export interface PdfDocument {
  setFont(font: string, style?: string): void;
  setFontSize(size: number): void;
  getTextWidth(text: string): number;
  splitTextToSize(text: string, maxWidth: number): string[];
  setTextColor(r: number, g: number, b: number): void;
  setDrawColor(r: number, g: number, b: number): void;
  setLineWidth(width: number): void;
  setFillColor(r: number, g: number, b: number): void;
  line(x1: number, y1: number, x2: number, y2: number): void;
  rect(x: number, y: number, w: number, h: number, style?: 'S' | 'F' | 'FD' | 'FS'): void;
  text(text: string, x: number, y: number, options?: { align?: 'left' | 'center' | 'right' }): void;
  addPage(): void;
  output(type: 'arraybuffer'): ArrayBuffer;
}

export interface RenderDigestPdfOptions {
  /** Total page count; when omitted the footer shows the current page only. */
  totalPages?: number;
}

export interface RenderDigestPdfResult {
  pages: number;
  unsupportedText: boolean;
}

const PAGE_W = 595.28;
const PAGE_H = 841.89;
const MARGIN_X = 14;
const MARGIN_TOP = 14;
const MARGIN_BOTTOM = 32;
const CONTENT_W = PAGE_W - MARGIN_X * 2;
const FOOTER_Y = PAGE_H - 20;

type Rgb = [number, number, number];

const COLOR_TITLE: Rgb = [24, 26, 30];
const COLOR_TEXT: Rgb = [52, 56, 62];
const COLOR_MUTED: Rgb = [112, 118, 128];
const COLOR_BORDER: Rgb = [206, 209, 214];
const COLOR_HEADER_BG: Rgb = [243, 244, 246];
const COLOR_EXPIRED: Rgb = [138, 28, 28];
const COLOR_TODAY: Rgb = [179, 38, 30];
const COLOR_SOON: Rgb = [138, 90, 0];

const SUMMARY_COL_WIDTHS = [26, 0, 62, 44, 76];
const LABEL_COL_W = 168;
const VALUE_GAP = 8;
const VALUE_COL_W = CONTENT_W - LABEL_COL_W - VALUE_GAP;

function statusColor(status: ReportEntry['status']): Rgb {
  if (status === 'Expired') {
    return COLOR_EXPIRED;
  }
  if (status === 'Expires today') {
    return COLOR_TODAY;
  }
  return COLOR_SOON;
}

interface Layout {
  doc: PdfDocument;
  y: number;
  page: number;
  totalPages: number;
  unsupported: boolean;
}

function clean(text: string): string {
  return text;
}

function setFont(doc: PdfDocument, bold: boolean, size: number): void {
  doc.setFont('helvetica', bold ? 'bold' : 'normal');
  doc.setFontSize(size);
}

function drawText(
  layout: Layout,
  text: string,
  x: number,
  size: number,
  bold: boolean,
  color: Rgb,
  align: 'left' | 'center' | 'right' = 'left',
): number {
  const sanitized = sanitizePdfText(text);
  if (sanitized.unsupported) {
    layout.unsupported = true;
  }
  setFont(layout.doc, bold, size);
  layout.doc.setTextColor(color[0], color[1], color[2]);
  layout.doc.text(sanitized.text, x, layout.y, { align });
  return layout.doc.getTextWidth(sanitized.text);
}

function drawFooter(layout: Layout): void {
  const doc = layout.doc;
  setFont(doc, false, 8);
  doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
  doc.text('Generated by DKS', MARGIN_X, FOOTER_Y);
  const total = layout.totalPages > 0 ? layout.totalPages : layout.page;
  doc.text(`Page ${layout.page} of ${total}`, PAGE_W - MARGIN_X, FOOTER_Y, { align: 'right' });
}

function ensureSpace(layout: Layout, height: number): void {
  if (layout.y + height <= PAGE_H - MARGIN_BOTTOM) {
    return;
  }
  drawFooter(layout);
  layout.doc.addPage();
  layout.page += 1;
  layout.y = MARGIN_TOP;
}

/** Draw a wrapped paragraph and advance the cursor. Returns the height used. */
function drawParagraph(
  layout: Layout,
  text: string,
  x: number,
  width: number,
  size: number,
  bold: boolean,
  color: [number, number, number],
  lineHeightFactor = 1.35,
): number {
  const sanitized = sanitizePdfText(text);
  if (sanitized.unsupported) {
    layout.unsupported = true;
  }
  const lineHeight = size * lineHeightFactor;
  setFont(layout.doc, bold, size);
  const lines = layout.doc.splitTextToSize(sanitized.text, width);
  const drawn = lines.length > 0 ? lines : [''];
  for (const line of drawn) {
    ensureSpace(layout, lineHeight);
    layout.doc.setTextColor(color[0], color[1], color[2]);
    layout.doc.text(line, x, layout.y);
    layout.y += lineHeight;
  }
  return drawn.length * lineHeight;
}

function drawSummaryTable(layout: Layout, model: DigestReportModel): void {
  const { doc } = layout;
  const recordWidth = CONTENT_W - SUMMARY_COL_WIDTHS.reduce((sum, width) => sum + width, 0);
  const widths = [...SUMMARY_COL_WIDTHS];
  widths[1] = recordWidth;
  const xPositions: number[] = [];
  let cursor = MARGIN_X;
  for (const width of widths) {
    xPositions.push(cursor);
    cursor += width;
  }

  const size = 9;
  const lineHeight = size * 1.3;
  const padding = 5;

  // Header.
  setFont(doc, true, size);
  doc.setFillColor(COLOR_HEADER_BG[0], COLOR_HEADER_BG[1], COLOR_HEADER_BG[2]);
  doc.rect(MARGIN_X, layout.y - size, CONTENT_W, size + padding * 2, 'F');
  const header = ['#', 'Record', 'Expiry', 'Days left', 'Status'];
  header.forEach((label, index) => {
    const sanitized = sanitizePdfText(label);
    if (sanitized.unsupported) {
      layout.unsupported = true;
    }
    doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
    doc.text(sanitized.text, xPositions[index] + padding, layout.y);
  });
  layout.y += size + padding * 2;

  doc.setDrawColor(COLOR_BORDER[0], COLOR_BORDER[1], COLOR_BORDER[2]);
  doc.setLineWidth(0.4);

  for (let index = 0; index < model.entries.length; index += 1) {
    const entry = model.entries[index];
    const cells = [
      String(index + 1),
      entry.label,
      entry.expiry.replace(/-/g, '/'),
      String(entry.daysLeft),
      entry.status,
    ];
    const wrapped: string[][] = cells.map((cell, cellIndex) => {
      const sanitized = sanitizePdfText(cell);
      if (sanitized.unsupported) {
        layout.unsupported = true;
      }
      setFont(doc, cellIndex === 4, size);
      return doc.splitTextToSize(sanitized.text, widths[cellIndex] - padding * 2);
    });
    const rowHeight = Math.max(...wrapped.map((lines) => lines.length)) * lineHeight + padding;
    ensureSpace(layout, rowHeight);

    wrapped.forEach((lines, cellIndex) => {
      const color = cellIndex === 4 ? statusColor(entry.status) : COLOR_TEXT;
      setFont(doc, cellIndex === 4, size);
      doc.setTextColor(color[0], color[1], color[2]);
      lines.forEach((line, lineIndex) => {
        doc.text(line, xPositions[cellIndex] + padding, layout.y + lineIndex * lineHeight);
      });
    });
    layout.y += rowHeight;
    doc.line(MARGIN_X, layout.y, MARGIN_X + CONTENT_W, layout.y);
  }
}

function measureBlockHeight(
  doc: PdfDocument,
  entry: ReportEntry,
  columns: readonly ReportColumn[],
  model: DigestReportModel,
): number {
  const size = 9.5;
  const lineHeight = size * 1.35;
  let height = 13 + 5; // header line + divider gap
  for (const column of columns) {
    const value = formatReportValue(
      resolveEntryValue(entry.data, column),
      column,
      { includeFullIds: model.includeFullIds, currency: model.currency, asciiSafe: true },
    );
    const valueLines = doc.splitTextToSize(sanitizePdfText(value).text || EMPTY_VALUE, VALUE_COL_W);
    const labelLines = doc.splitTextToSize(sanitizePdfText(column.name).text, LABEL_COL_W);
    height += Math.max(valueLines.length, labelLines.length, 1) * lineHeight + 1.5;
  }
  return height + 8;
}

function drawDetailBlock(
  layout: Layout,
  entry: ReportEntry,
  columns: readonly ReportColumn[],
  model: DigestReportModel,
  index: number,
): void {
  const { doc } = layout;

  const blockHeight = measureBlockHeight(doc, entry, columns, model);
  if (layout.y + blockHeight > PAGE_H - MARGIN_BOTTOM && layout.y > MARGIN_TOP) {
    drawFooter(layout);
    doc.addPage();
    layout.page += 1;
    layout.y = MARGIN_TOP;
  }

  // Header: "N. label — Expiry DD/MM/YYYY — N days left" + right-aligned status.
  setFont(doc, true, 10.5);
  const leftText = `${index + 1}. ${entry.label} — Expiry ${entry.expiry.replace(/-/g, '/')} — ${entry.daysLeft} days left`;
  const leftWidth = drawText(layout, leftText, MARGIN_X, 10.5, true, COLOR_TITLE);
  void leftWidth;
  const statusColorValue = statusColor(entry.status);
  setFont(doc, true, 10.5);
  doc.setTextColor(statusColorValue[0], statusColorValue[1], statusColorValue[2]);
  doc.text(entry.status, PAGE_W - MARGIN_X, layout.y, { align: 'right' });
  layout.y += 13;

  doc.setDrawColor(COLOR_BORDER[0], COLOR_BORDER[1], COLOR_BORDER[2]);
  doc.setLineWidth(0.5);
  doc.line(MARGIN_X, layout.y, MARGIN_X + CONTENT_W, layout.y);
  layout.y += 6;

  for (const column of columns) {
    const value = formatReportValue(
      resolveEntryValue(entry.data, column),
      column,
      { includeFullIds: model.includeFullIds, currency: model.currency, asciiSafe: true },
    );
    const valueLines = doc.splitTextToSize(sanitizePdfText(value).text || EMPTY_VALUE, VALUE_COL_W);
    const labelLines = doc.splitTextToSize(sanitizePdfText(column.name).text, LABEL_COL_W);
    const rows = Math.max(valueLines.length, labelLines.length, 1);
    const rowHeight = rows * (9.5 * 1.35);
    ensureSpace(layout, rowHeight);

    setFont(doc, true, 9);
    doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
    labelLines.forEach((line, lineIndex) => {
      doc.text(line, MARGIN_X, layout.y + lineIndex * (9.5 * 1.35));
    });

    setFont(doc, false, 9.5);
    doc.setTextColor(COLOR_TEXT[0], COLOR_TEXT[1], COLOR_TEXT[2]);
    const valueX = MARGIN_X + LABEL_COL_W + VALUE_GAP;
    valueLines.forEach((line, lineIndex) => {
      doc.text(line, valueX, layout.y + lineIndex * (9.5 * 1.35));
    });
    layout.y += rowHeight;
  }

  layout.y += 6;
}

function drawTitle(layout: Layout, model: DigestReportModel): void {
  const { doc } = layout;
  setFont(doc, true, 17);
  doc.setTextColor(COLOR_TITLE[0], COLOR_TITLE[1], COLOR_TITLE[2]);
  doc.text('DKS Daily Expiry Report', MARGIN_X, layout.y);
  layout.y += 8;

  setFont(doc, false, 10);
  doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
  doc.text(`Report date: ${model.reportDateDisplay}`, MARGIN_X, layout.y);
  layout.y += 6;

  const { summary } = model;
  doc.text(
    `Total listed: ${summary.total} · Expired: ${summary.expired} · Expires today: ${summary.today} · `
    + `Within 7 days: ${summary.within7} · Within 30 days: ${summary.within30}`,
    MARGIN_X,
    layout.y,
  );
  layout.y += 10;

  if (model.truncated) {
    drawParagraph(
      layout,
      `This report shows the ${model.entries.length} most urgent of ${model.totalQualifying} `
      + 'records expiring within 30 days.',
      MARGIN_X,
      CONTENT_W,
      9,
      false,
      COLOR_MUTED,
    );
    layout.y += 4;
  }

  if (!model.includeFullIds && model.columns.some((column) => column.sensitive)) {
    drawParagraph(
      layout,
      'Passport and Civil ID values are masked (last 4 digits only).',
      MARGIN_X,
      CONTENT_W,
      9,
      false,
      COLOR_MUTED,
    );
    layout.y += 4;
  }
}

function drawEmptyState(layout: Layout): void {
  const { doc } = layout;
  setFont(doc, true, 13);
  doc.setTextColor(COLOR_TITLE[0], COLOR_TITLE[1], COLOR_TITLE[2]);
  doc.text('All clear — nothing expiring within the next 30 days.', MARGIN_X, layout.y);
  layout.y += 8;
  setFont(doc, false, 10);
  doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
  doc.text('No records match the daily expiry report window.', MARGIN_X, layout.y);
}

/**
 * Render the report into `doc`. `options.totalPages` is the final page count
 * (from a first pass) so the footer can print "Page X of Y".
 */
export function renderDigestPdf(
  doc: PdfDocument,
  model: DigestReportModel,
  options: RenderDigestPdfOptions = {},
): RenderDigestPdfResult {
  const layout: Layout = {
    doc,
    y: MARGIN_TOP,
    page: 1,
    totalPages: options.totalPages ?? 0,
    unsupported: false,
  };

  drawTitle(layout, model);
  layout.y += 2;

  if (model.entries.length === 0) {
    drawEmptyState(layout);
    drawFooter(layout);
    return { pages: layout.page, unsupportedText: layout.unsupported };
  }

  drawSummaryTable(layout, model);
  layout.y += 12;

  const detailEntries = model.entries.slice(0, MAX_DETAIL_RECORDS);
  for (let index = 0; index < detailEntries.length; index += 1) {
    drawDetailBlock(layout, detailEntries[index], model.columns, model, index);
  }
  if (model.entries.length > detailEntries.length) {
    drawParagraph(
      layout,
      `Detail blocks are truncated to the first ${MAX_DETAIL_RECORDS} records; `
      + `${model.entries.length - MAX_DETAIL_RECORDS} more are listed in the summary above.`,
      MARGIN_X,
      CONTENT_W,
      9,
      false,
      COLOR_MUTED,
    );
  }

  drawFooter(layout);
  return { pages: layout.page, unsupportedText: layout.unsupported };
}
