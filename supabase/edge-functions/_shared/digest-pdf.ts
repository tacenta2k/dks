function measureWidths(doc: PdfDocument, table: GridTable): number[] {
  return table.columns.map((def, index) => {
    setFont(doc, true, GRID_SIZE);
    let natural = doc.getTextWidth(sanitizePdfText(def.header).text);
    for (const row of table.rows) {
      setFont(doc, false, GRID_SIZE);
      natural = Math.max(natural, doc.getTextWidth(sanitizePdfText(row.cells[index] ?? '').text));
    }
    const minimum = def.kind === 'label' ? MIN_LABEL_W : MIN_COL_W;
    const maximum = def.kind === 'label' ? MAX_LABEL_W : MAX_COL_W;
    return Math.min(Math.max(Math.ceil(natural + CELL_PAD_X * 2 + 1), minimum), maximum);
  });
}

/**
 * Pack columns into groups that each fit one landscape page. The record label
 * is prepended to EVERY group, so a reader can always tell which record a
 * continued column block belongs to.
 */
export function planGridGroups(doc: PdfDocument, table: GridTable): GridGroup[] {
  const natural = measureWidths(doc, table);
  const labelWidth = natural[0] ?? MIN_LABEL_W;

  const groups: number[][] = [];
  let current: number[] = [];
  let used = labelWidth;
  for (let index = 1; index < natural.length; index += 1) {
    if (current.length > 0 && used + natural[index] > CONTENT_W) {
      groups.push(current);
      current = [];
      used = labelWidth;
    }
    current.push(index);
    used += natural[index];
  }
  groups.push(current);

  const packed = groups.filter((group) => group.length > 0);
  // A sheet with no user columns still gets one group: just the record label.
  const layouts: number[][] = packed.length > 0 ? packed : [[]];
  const total = layouts.length;

  return layouts.map((groupIndexes, groupIndex) => {
    const indexes = [0, ...groupIndexes];
    const widths = indexes.map((columnIndex) => natural[columnIndex]);
    // Fill the page: scale up proportionally when the group leaves slack, so
    // the table always uses the full landscape width.
    const usedWidth = widths.reduce((sum, width) => sum + width, 0);
    const factor = usedWidth > 0 && usedWidth < CONTENT_W ? CONTENT_W / usedWidth : 1;
    const columns = indexes.map((columnIndex, position) => ({
      ...table.columns[columnIndex],
      header: position === 0 && groupIndex > 0
        ? `${table.columns[0].header} (continued)`
        : table.columns[columnIndex].header,
    }));
    return {
      index: groupIndex + 1,
      total,
      columns,
      columnIndexes: indexes,
      widths: widths.map((width) => width * factor),
    };
  });
}

function cellColor(def: GridColumnDef, entry: ReportEntry): Rgb {
  if (def.kind === 'status' || def.kind === 'daysLeft') {
    return statusColor(entry.daysLeft);
  }
  if (def.kind === 'expiry' && isCriticalDaysLeft(entry.daysLeft)) {
    return statusColor(entry.daysLeft);
  }
  return COLOR_TEXT;
}

function drawTableHeader(layout: Layout, group: GridGroup): void {
  const { doc } = layout;
  const wrapped = group.columns.map((def, index) => (
    wrapText(layout, def.header, group.widths[index] - CELL_PAD_X * 2, true)
  ));
  const lines = Math.max(...wrapped.map((entry) => entry.length), 1);
  const height = lines * GRID_LINE_H + CELL_PAD_Y * 2;

  ensureSpace(layout, height + GRID_LINE_H);
  doc.setFillColor(COLOR_HEADER_BG[0], COLOR_HEADER_BG[1], COLOR_HEADER_BG[2]);
  doc.rect(MARGIN_X, layout.y, CONTENT_W, height, 'F');

  let x = MARGIN_X;
  group.columns.forEach((def, index) => {
    const width = group.widths[index];
    doc.setDrawColor(COLOR_BORDER[0], COLOR_BORDER[1], COLOR_BORDER[2]);
    doc.setLineWidth(0.3);
    doc.rect(x, layout.y, width, height, 'S');
    wrapped[index].forEach((line, lineIndex) => {
      drawText(layout, line, x + CELL_PAD_X, layout.y + CELL_PAD_Y + GRID_LINE_H * (lineIndex + 0.85), {
        size: GRID_SIZE,
        bold: true,
        color: COLOR_TITLE,
      });
    });
    x += width;
  });

  layout.y += height;
}

function drawTableRow(
  layout: Layout,
  group: GridGroup,
  row: GridRow,
  rowIndex: number,
): void {
  const { doc } = layout;
  const wrapped = group.columns.map((def, index) => (
    wrapText(layout, row.cells[group.columnIndexes[index]] ?? '', group.widths[index] - CELL_PAD_X * 2)
  ));
  const lines = Math.max(...wrapped.map((entry) => entry.length), 1);
  const height = lines * GRID_LINE_H + CELL_PAD_Y * 2;

  if (layout.y + height > PAGE_H - MARGIN_BOTTOM) {
    addPage(layout);
    drawTableHeader(layout, group);
  }

  // Alternate shading (even rows stay white, odd rows get a light grey band).
  if (rowIndex % 2 === 1) {
    doc.setFillColor(COLOR_ROW_ALT[0], COLOR_ROW_ALT[1], COLOR_ROW_ALT[2]);
    doc.rect(MARGIN_X, layout.y, CONTENT_W, height, 'F');
  }

  let x = MARGIN_X;
  group.columns.forEach((def, index) => {
    const width = group.widths[index];
    doc.setDrawColor(COLOR_BORDER[0], COLOR_BORDER[1], COLOR_BORDER[2]);
    doc.setLineWidth(0.25);
    doc.rect(x, layout.y, width, height, 'S');
    const color = cellColor(def, row.entry);
    wrapped[index].forEach((line, lineIndex) => {
      drawText(layout, line, x + CELL_PAD_X, layout.y + CELL_PAD_Y + GRID_LINE_H * (lineIndex + 0.85), {
        size: GRID_SIZE,
        bold: def.kind === 'label' || def.kind === 'status' || def.kind === 'daysLeft',
        color,
      });
    });
    x += width;
  });

  layout.y += height;
  doc.setDrawColor(COLOR_BORDER[0], COLOR_BORDER[1], COLOR_BORDER[2]);
  doc.setLineWidth(0.3);
  doc.line(MARGIN_X, layout.y, MARGIN_X + CONTENT_W, layout.y);
}

function drawTable(layout: Layout, table: GridTable, group: GridGroup): void {
  drawTableHeader(layout, group);
  table.rows.forEach((row, rowIndex) => {
    drawTableRow(layout, group, row, rowIndex);
  });
}

function drawContinuedHeading(layout: Layout, model: DigestReportModel, group: GridGroup): void {
  drawText(layout, 'DKS Daily Expiry Report', MARGIN_X, layout.y + 10, {
    size: 13,
    bold: true,
    color: COLOR_TITLE,
  });
  drawText(layout, `Report date: ${reportStamp(model)}`, PAGE_W - MARGIN_X, layout.y + 10, {
    size: 9,
    color: COLOR_MUTED,
    align: 'right',
  });
  layout.y += 16;
  drawText(
    layout,
    `Visa Sheet columns continued — group ${group.index} of ${group.total}`,
    MARGIN_X,
    layout.y + 8,
    { size: 9, bold: true, color: COLOR_MUTED },
  );
  layout.y += 16;
}

function drawEmptyState(layout: Layout): void {
  layout.y += 10;
  drawText(layout, 'No expiries to flag today', MARGIN_X, layout.y, {
    size: 15,
    bold: true,
    color: COLOR_TITLE,
  });
  layout.y += 12;
  drawParagraph(layout, 'All clear — nothing expiring within the next 30 days.', {
    size: 10,
    color: COLOR_MUTED,
  });
}

function drawClosingNotes(layout: Layout, model: DigestReportModel): void {
  const notes: string[] = [];
  const truncation = truncationNote(model);
  if (truncation) {
    notes.push(truncation);
  }
  if (layout.unsupported) {
    notes.push(
      "Some characters in this report cannot be encoded by the PDF font and are shown as '?'.",
    );
  }
  if (notes.length === 0) {
    return;
  }
  layout.y += 6;
  for (const note of notes) {
    drawParagraph(layout, note, { size: 8.5, color: COLOR_MUTED });
  }
}

/**
 * Render the report into `doc`. `options.totalPages` is the final page count
 * (from a first pass) so the footer can print "Page X of Y".
 */
export function renderDigestPdf(
  doc: PdfDocument,
  model: DigestReportModel,
  options: RenderDigestPdfOptions = {},
): RenderDigestPdfResult {
  const layout: Layout = {
    doc,
    y: MARGIN_TOP,
    page: 1,
    totalPages: options.totalPages ?? 0,
    unsupported: false,
    model,
  };

  const table = buildGridTable(model);

  if (model.entries.length === 0) {
    drawTitleBlock(layout, model);
    drawEmptyState(layout);
    drawFooter(layout);
    return { pages: layout.page, unsupportedText: layout.unsupported };
  }

  drawTitleBlock(layout, model);

  const groups = planGridGroups(doc, table);
  for (const group of groups) {
    if (group.index > 1) {
      addPage(layout);
      drawContinuedHeading(layout, model, group);
    }
    drawTable(layout, table, group);
  }

  drawClosingNotes(layout, model);
  drawFooter(layout);
  return { pages: layout.page, unsupportedText: layout.unsupported };
}
