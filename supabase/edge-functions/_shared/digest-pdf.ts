/**
 * DKS daily expiry report — landscape A4 GRID renderer.
 *
 * Pure TypeScript: it draws through a tiny `PdfDocument` interface so the SAME
 * layout code is unit tested with vitest (with real jsPDF from node_modules)
 * and bundled into the `send-email` Edge Function (Deno, `npm:jspdf`).
 *
 * The PDF is generated entirely in memory and handed back as bytes; nothing is
 * written to disk, Supabase Storage, or any database table.
 *
 * Layout — an Excel-like table, not a summary + detail-block document:
 *   - landscape A4 (`841.89 × 595.28 pt`);
 *   - summary counts on top (Expired · Today · Next 7 · Next 30 · Total);
 *   - one row per record; one column per VISIBLE Visa Sheet column in the
 *     sheet's saved `position` order, then Expiry (DD/MM/YYYY), Days left and
 *     Status — no column is ever dropped;
 *   - column widths auto-sized from the widest cell, clamped between a minimum
 *     and a maximum, with wrapping (never truncation);
 *   - when the columns are wider than one landscape page, the table is split
 *     into COLUMN GROUPS rendered on successive pages, and the record name is
 *     repeated as the first column of every group (`Record (continued)`);
 *   - the header row is redrawn on every page;
 *   - alternate row shading and status colours (expired/today red, 1..7 amber,
 *     everything else neutral) — the status is always TEXT as well;
 *   - footer on every page: "Generated by DKS", the report date/time in
 *     Asia/Muscat, and "Page X of Y";
 *   - the 200-row cap is stated on the last page when it applies.
 *
 * Text limitation: the PDF uses the standard WinAnsi fonts, which cannot encode
 * non-Latin scripts (e.g. Arabic). Such characters are replaced with a visible
 * "?" AND the document prints an explicit notice — never silent blanks. A
 * currency symbol that cannot be encoded falls back to the ISO code and the
 * report says so.
 */

import {
  DKS_BUSINESS_TIME_ZONE,
  formatDaysLeft,
  formatReportValue,
  isCriticalDaysLeft,
  isSoonDaysLeft,
  resolveEntryValue,
  sanitizePdfText,
  summaryCountItems,
  truncationNote,
  currencyFallbackNote,
  maskingNote,
  type DigestReportModel,
  type ReportColumn,
  type ReportEntry,
} from './digest-report.ts';

export interface PdfDocument {
  setFont(font: string, style?: string): void;
  setFontSize(size: number): void;
  getTextWidth(text: string): number;
  splitTextToSize(text: string, maxWidth: number): string[];
  setTextColor(r: number, g: number, b: number): void;
  setDrawColor(r: number, g: number, b: number): void;
  setLineWidth(width: number): void;
  setFillColor(r: number, g: number, b: number): void;
  line(x1: number, y1: number, x2: number, y2: number): void;
  rect(x: number, y: number, w: number, h: number, style?: 'S' | 'F' | 'FD' | 'FS'): void;
  text(text: string, x: number, y: number, options?: { align?: 'left' | 'center' | 'right' }): void;
  addPage(): void;
  output(type: 'arraybuffer'): ArrayBuffer;
}

export interface RenderDigestPdfOptions {
  /** Total page count; when omitted the footer shows the current page only. */
  totalPages?: number;
}

export interface RenderDigestPdfResult {
  pages: number;
  unsupportedText: boolean;
}

/**
 * jsPDF page configuration. `unit: 'pt'` is essential: jsPDF defaults to
 * millimetres, and this layout works in PDF points — with the default unit the
 * whole page was drawn at 2.83x scale and the footer fell off the page.
 */
export const PDF_DOCUMENT_OPTIONS = {
  orientation: 'landscape',
  unit: 'pt',
  format: 'a4',
} as const;

/** Landscape A4, in points. */
const PAGE_W = 841.89;
const PAGE_H = 595.28;
const MARGIN_X = 22;
const MARGIN_TOP = 18;
const MARGIN_BOTTOM = 34;
const CONTENT_W = PAGE_W - MARGIN_X * 2;
const FOOTER_Y = PAGE_H - 18;

const GRID_SIZE = 7.5;
const GRID_LINE_H = GRID_SIZE * 1.32;
const CELL_PAD_X = 3;
const CELL_PAD_Y = 2.4;
const MIN_COL_W = 42;
const MAX_COL_W = 150;
const MIN_LABEL_W = 92;
const MAX_LABEL_W = 150;

type Rgb = [number, number, number];

const COLOR_TITLE: Rgb = [24, 26, 30];
const COLOR_TEXT: Rgb = [52, 56, 62];
const COLOR_MUTED: Rgb = [112, 118, 128];
const COLOR_BORDER: Rgb = [199, 203, 209];
const COLOR_HEADER_BG: Rgb = [233, 236, 240];
const COLOR_SUMMARY_BG: Rgb = [247, 248, 250];
const COLOR_ROW_ALT: Rgb = [249, 250, 251];
const COLOR_ROW_WHITE: Rgb = [255, 255, 255];
const COLOR_EXPIRED: Rgb = [138, 28, 28];
const COLOR_TODAY: Rgb = [179, 38, 30];
const COLOR_SOON: Rgb = [138, 90, 0];

export type GridColumnKind = 'label' | 'value' | 'expiry' | 'daysLeft' | 'status';

export interface GridColumnDef {
  /** Stable key, e.g. `col:<column id>`, `expiry`, `daysLeft`, `status`. */
  key: string;
  header: string;
  kind: GridColumnKind;
  /** Present for `kind === 'value'` (a real Visa Sheet column). */
  column?: ReportColumn;
}

export interface GridRow {
  entry: ReportEntry;
  /** One already-formatted cell per column, in `GridColumnDef` order. */
  cells: string[];
}

export interface GridTable {
  columns: GridColumnDef[];
  rows: GridRow[];
}

export interface GridGroup {
  /** 1-based group ordinal (e.g. 2 of 3). */
  index: number;
  total: number;
  columns: GridColumnDef[];
  /** Index into the full `GridTable.columns` / `GridRow.cells` arrays. */
  columnIndexes: number[];
  widths: number[];
}

function statusColor(daysLeft: number): Rgb {
  if (daysLeft < 0) {
    return COLOR_EXPIRED;
  }
  if (daysLeft === 0) {
    return COLOR_TODAY;
  }
  return isSoonDaysLeft(daysLeft) ? COLOR_SOON : COLOR_TEXT;
}

/**
 * Every printed column, in order: the record label first (repeated per column
 * group), then EVERY visible Visa Sheet column in the sheet's saved order,
 * then the report-managed Expiry / Days left / Status columns.
 */
export function buildGridColumns(model: DigestReportModel): GridColumnDef[] {
  return [
    { key: 'label', header: 'Record', kind: 'label' },
    ...model.columns.map((column) => ({
      key: `col:${column.id}`,
      header: column.name,
      kind: 'value' as const,
      column,
    })),
    { key: 'expiry', header: 'Expiry', kind: 'expiry' },
    { key: 'daysLeft', header: 'Days left', kind: 'daysLeft' },
    { key: 'status', header: 'Status', kind: 'status' },
  ];
}

function cellValue(def: GridColumnDef, entry: ReportEntry, model: DigestReportModel): string {
  switch (def.kind) {
    case 'label':
      return entry.label;
    case 'expiry':
      return entry.expiry.replace(/^(\d{4})-(\d{2})-(\d{2})$/, '$3/$2/$1');
    case 'daysLeft':
      return formatDaysLeft(entry.daysLeft);
    case 'status':
      return entry.status;
    default: {
      const column = def.column as ReportColumn;
      return formatReportValue(resolveEntryValue(entry.data, column), column, {
        includeFullIds: model.includeFullIds,
        currency: model.currency,
        asciiSafe: true,
      });
    }
  }
}

export function buildGridTable(model: DigestReportModel): GridTable {
  const columns = buildGridColumns(model);
  const rows = model.entries.map((entry) => ({
    entry,
    cells: columns.map((def) => cellValue(def, entry, model)),
  }));
  return { columns, rows };
}

// ---------------------------------------------------------------------------
// Layout plumbing
// ---------------------------------------------------------------------------

interface Layout {
  doc: PdfDocument;
  y: number;
  page: number;
  totalPages: number;
  unsupported: boolean;
  model: DigestReportModel;
}

function setFont(doc: PdfDocument, bold: boolean, size: number): void {
  doc.setFont('helvetica', bold ? 'bold' : 'normal');
  doc.setFontSize(size);
}

/** Sanitise for the WinAnsi font and remember that a substitution happened. */
function safeText(layout: Layout, text: string): string {
  const sanitized = sanitizePdfText(text);
  if (sanitized.unsupported) {
    layout.unsupported = true;
  }
  return sanitized.text;
}

function drawText(
  layout: Layout,
  text: string,
  x: number,
  y: number,
  options: { size: number; bold?: boolean; color?: Rgb; align?: 'left' | 'right' | 'center' },
): number {
  const value = safeText(layout, text);
  setFont(layout.doc, options.bold === true, options.size);
  const color = options.color ?? COLOR_TEXT;
  layout.doc.setTextColor(color[0], color[1], color[2]);
  layout.doc.text(value, x, y, options.align ? { align: options.align } : undefined);
  return layout.doc.getTextWidth(value);
}

function reportStamp(model: DigestReportModel): string {
  return `${model.reportDateTimeDisplay || model.reportDateDisplay} (${DKS_BUSINESS_TIME_ZONE})`;
}

function drawFooter(layout: Layout): void {
  const { doc } = layout;
  setFont(doc, false, 7.5);
  doc.setTextColor(COLOR_MUTED[0], COLOR_MUTED[1], COLOR_MUTED[2]);
  doc.text('Generated by DKS', MARGIN_X, FOOTER_Y);
  doc.text(`Report date: ${reportStamp(layout.model)}`, PAGE_W / 2, FOOTER_Y, { align: 'center' });
  const total = layout.totalPages > 0 ? layout.totalPages : layout.page;
  doc.text(`Page ${layout.page} of ${total}`, PAGE_W - MARGIN_X, FOOTER_Y, { align: 'right' });
}

function addPage(layout: Layout): void {
  drawFooter(layout);
  layout.doc.addPage();
  layout.page += 1;
  layout.y = MARGIN_TOP;
}

function ensureSpace(layout: Layout, height: number): void {
  if (layout.y + height <= PAGE_H - MARGIN_BOTTOM) {
    return;
  }
  addPage(layout);
}

/**
 * Wrap text into `width`. `splitTextToSize` handles word wrapping; a single
 * token that is still too wide is hard-split by characters so a long value can
 * never overflow its cell or be dropped.
 */
function wrapText(layout: Layout, text: string, width: number, bold = false, size = GRID_SIZE): string[] {
  const safe = safeText(layout, text);
  setFont(layout.doc, bold, size);
  const lines = layout.doc.splitTextToSize(safe, width);
  const out: string[] = [];
  for (const line of lines.length > 0 ? lines : ['']) {
    if (layout.doc.getTextWidth(line) <= width || line.length <= 1) {
      out.push(line);
      continue;
    }
    let chunk = '';
    for (const char of line) {
      const candidate = chunk + char;
      if (chunk !== '' && layout.doc.getTextWidth(candidate) > width) {
        out.push(chunk);
        chunk = char;
      } else {
        chunk = candidate;
      }
    }
    if (chunk !== '') {
      out.push(chunk);
    }
  }
  return out;
}

/** Wrapped paragraph that advances the cursor; used for notes only. */
function drawParagraph(
  layout: Layout,
  text: string,
  options: { size: number; bold?: boolean; color?: Rgb },
): void {
  const lines = wrapText(layout, text, CONTENT_W, options.bold === true, options.size);
  const lineHeight = options.size * 1.35;
  for (const line of lines) {
    ensureSpace(layout, lineHeight);
    drawText(layout, line, MARGIN_X, layout.y, options);
    layout.y += lineHeight;
  }
}

// ---------------------------------------------------------------------------
// Header block (first page only)
// ---------------------------------------------------------------------------

function drawSummaryStrip(layout: Layout): void {
  const { doc, model } = layout;
  const height = 20;
  const items = summaryCountItems(model);
  doc.setFillColor(COLOR_SUMMARY_BG[0], COLOR_SUMMARY_BG[1], COLOR_SUMMARY_BG[2]);
  doc.rect(MARGIN_X, layout.y, CONTENT_W, height, 'F');

  const baseline = layout.y + height - 6;
  let x = MARGIN_X + 8;
  for (const item of items) {
    const labelWidth = drawText(layout, `${item.label}:`, x, baseline, {
      size: 9,
      bold: false,
      color: COLOR_MUTED,
    });
    x += labelWidth + 4;
    const valueWidth = drawText(layout, String(item.value), x, baseline, {
      size: 10,
      bold: true,
      color: item.label === 'Expired' || item.label === 'Today' ? COLOR_TODAY : COLOR_TITLE,
    });
    x += valueWidth + 18;
  }
  layout.y += height;
}

function drawTitleBlock(layout: Layout, model: DigestReportModel): void {
  drawText(layout, 'DKS Daily Expiry Report', MARGIN_X, layout.y + 12, {
    size: 16,
    bold: true,
    color: COLOR_TITLE,
  });
  drawText(layout, `Report date: ${reportStamp(model)}`, PAGE_W - MARGIN_X, layout.y + 12, {
    size: 9,
    color: COLOR_MUTED,
    align: 'right',
  });
  layout.y += 20;

  layout.y += 4;
  drawSummaryStrip(layout);
  layout.y += 6;

  for (const note of [maskingNote(model), currencyFallbackNote(model)]) {
    if (!note) {
      continue;
    }
    drawParagraph(layout, note, { size: 8.5, color: COLOR_MUTED });
  }

  layout.y += 4;
}

